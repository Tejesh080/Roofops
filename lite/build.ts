import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadConfig, type LiteConfig } from './config/config.js';
import { loadWorkflow } from './tools/load-workflow.js';
import type { RecEdge, RecNode } from './tools/sdk-recorder.js';

export const SRC = 'lite/n8n/src';
export const WORKFLOWS = ['lead-follow-up', 'review-requests', 'lead-reactivation', 'inbound-replies', 'monitor'] as const;
const part = (f: string) => readFileSync(join(SRC, f), 'utf8');

/** The standalone SDK source of one workflow for this config. */
export function generateSdk(name: string, config: LiteConfig): string {
  let s = part(`${name}.sdk.ts`);
  const urls = Object.fromEntries(Object.entries(config.airtable.tables).map(([k, v]) => [k, `https://api.airtable.com/v0/${config.airtable.baseId}/${encodeURIComponent(v)}`]));
  const common = part('common.part.ts').replace('__LITE_CONFIG__', JSON.stringify(config, null, 2)).replace('__LITE_TABLE_URLS__', JSON.stringify(urls, null, 2));
  s = s.replace(/\/\/ @include ([a-z-]+)/g, (_m, inc: string) => `// ---- shared (lite/n8n/src/${inc}.part.ts) ----\n${inc === 'common' ? common : part(`${inc}.part.ts`)}// ---- end shared ----`);
  if (/@include|__LITE_CONFIG__|__LITE_TABLE_URLS__/.test(s)) throw new Error(`${name}: an include or the config placeholder was not replaced`);
  return `// GENERATED by lite/build.ts from ${SRC}/${name}.sdk.ts for "${config.business.name}". Do not edit; edit the source and rebuild.\n${s}`;
}

const uuid = (seed: string) => { const h = createHash('sha256').update(seed).digest('hex'); return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`; };

/** An n8n import JSON from what the workflow file declared. */
export function toN8nJson(meta: { id: string; name: string }, nodes: Map<string, RecNode>, edges: RecEdge[], settings: Record<string, unknown> = { executionOrder: 'v1' }) {
  // Lay nodes out left to right by distance from a trigger.
  const depth = new Map<string, number>();
  const starts = [...nodes.values()].filter((n) => !edges.some((e) => e.to === n.name)).map((n) => n.name);
  const queue: [string, number][] = starts.map((s) => [s, 0]);
  while (queue.length) {
    const [n, d] = queue.shift()!;
    if ((depth.get(n) ?? -1) >= d) continue;
    depth.set(n, d);
    if (d > nodes.size) continue;
    for (const e of edges.filter((x) => x.from === n)) queue.push([e.to, d + 1]);
  }
  const rows = new Map<number, number>();
  const out = [...nodes.values()].map((n) => {
    const d = depth.get(n.name) ?? 0; const r = rows.get(d) ?? 0; rows.set(d, r + 1);
    const c = n.config;
    const j: Record<string, unknown> = { id: uuid(`${meta.id}:${n.name}`), name: n.name, type: n.type, typeVersion: n.version, position: [d * 260, r * 180], parameters: c.parameters ?? {} };
    if (c.credentials) j.credentials = c.credentials;
    if (c.disabled) j.disabled = true;
    if (c.onError) j.onError = c.onError;
    if (n.type === 'n8n-nodes-base.webhook') j.webhookId = uuid(`${meta.id}:${n.name}:webhook`);
    return j;
  });
  const connections: Record<string, { main: { node: string; type: 'main'; index: number }[][] }> = {};
  for (const e of edges) {
    const slot = e.branch === 'false' || e.branch === 'error' ? 1 : 0;
    const c = (connections[e.from] ??= { main: [] });
    while (c.main.length <= slot) c.main.push([]);
    c.main[slot]!.push({ node: e.to, type: 'main', index: 0 });
  }
  return { name: meta.name, nodes: out, connections, active: false, settings, pinData: {}, tags: [],
    meta: { generatedBy: 'lite/build.ts', templateCredsSetupCompleted: false } };
}

/**
 * Flat n8n SDK code from a recorded workflow: one literal node()/trigger()/ifElse() per node and the connections, with
 * expressions written as expr(). n8n's SDK parser accepts no functions, so this is what n8n receives; the shared
 * helpers live only in the sources.
 */
export function emitSdk(meta: { id: string; name: string }, nodes: Map<string, RecNode>, edges: RecEdge[], header: string): string {
  const lit = (v: unknown, ind: string): string => {
    if (typeof v === 'string') return v.startsWith('=') ? `expr(${JSON.stringify(v.slice(1))})` : JSON.stringify(v);
    if (Array.isArray(v)) return v.length ? `[${v.map((x) => lit(x, ind)).join(', ')}]` : '[]';
    if (v && typeof v === 'object') {
      const e = Object.entries(v as Record<string, unknown>);
      return e.length ? `{\n${e.map(([k, x]) => `${ind}  ${JSON.stringify(k)}: ${lit(x, `${ind}  `)}`).join(',\n')}\n${ind}}` : '{}';
    }
    return JSON.stringify(v);
  };
  const vars = new Map([...nodes.keys()].map((n, i) => [n, `n${i}`]));
  const TRIGGERS = ['n8n-nodes-base.webhook', 'n8n-nodes-base.scheduleTrigger', 'n8n-nodes-base.manualTrigger', 'n8n-nodes-base.errorTrigger'];
  const decl = [...nodes.values()].map((n) => {
    const fn = n.type === 'n8n-nodes-base.if' ? 'ifElse' : TRIGGERS.includes(n.type) ? 'trigger' : 'node';
    const body = fn === 'ifElse' ? `{ version: ${n.version}, config: ${lit(n.config, '')} }` : `{ type: ${JSON.stringify(n.type)}, version: ${n.version}, config: ${lit(n.config, '')} }`;
    return `// ${n.name}\nconst ${vars.get(n.name)!} = ${fn}(${body});`;
  });
  const links: string[] = [];
  for (const e of edges.filter((x) => x.branch === 'main')) links.push(`  .add(${vars.get(e.from)!}).to(${vars.get(e.to)!})`);
  for (const n of [...nodes.values()].filter((x) => x.type === 'n8n-nodes-base.if')) {
    const t = edges.find((e) => e.from === n.name && e.branch === 'true'); const f = edges.find((e) => e.from === n.name && e.branch === 'false');
    if (t || f) links.push(`  .add(${vars.get(n.name)!}${t ? `.onTrue(${vars.get(t.to)!})` : ''}${f ? `.onFalse(${vars.get(f.to)!})` : ''})`);
  }
  if (edges.some((e) => !['main', 'true', 'false'].includes(e.branch))) throw new Error(`${meta.name}: unsupported connection kind`);
  return `${header}\nimport { workflow, node, trigger, ifElse, expr } from '@n8n/workflow-sdk';\n\n${decl.join('\n\n')}\n\nexport default workflow(${JSON.stringify(meta.id)}, ${JSON.stringify(meta.name)})\n${links.join('\n')};\n`;
}

export async function build(configFile: string, outDir?: string) {
  const config = loadConfig(configFile);
  const out = outDir ?? join('lite/dist', basename(configFile, '.json'));
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const summary: { workflow: string; name: string; nodes: number; connections: number }[] = [];
  for (const w of WORKFLOWS) {
    // Source (shared helpers + this config) -> recorded nodes and connections -> flat SDK code n8n accepts.
    const source = join(out, `${w}.source.sdk.ts`);
    writeFileSync(source, generateSdk(w, config));
    const r = await loadWorkflow(source);
    rmSync(source);
    const header = `// GENERATED by lite/build.ts from ${SRC}/${w}.sdk.ts for "${config.business.name}". Do not edit; edit the source and rebuild.\n// Inactive by design: import or create it in n8n, then activate only when you have approved live use.`;
    writeFileSync(join(out, `${w}.sdk.ts`), emitSdk(r.meta, r.nodes, r.edges, header));
    // The flat file must describe exactly the same workflow.
    const again = await loadWorkflow(join(out, `${w}.sdk.ts`));
    if (JSON.stringify([...again.nodes.values()]) !== JSON.stringify([...r.nodes.values()]) || JSON.stringify(again.edges.slice().sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))))
        !== JSON.stringify(r.edges.slice().sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))))) throw new Error(`${w}: the flat SDK file does not reproduce the workflow`);
    // Schedules run in the business timezone; failures of the others go to [Lite] Monitor once its id is in the config.
    const settings: Record<string, unknown> = { executionOrder: 'v1', timezone: config.business.timezone, saveManualExecutions: true };
    if (w !== 'monitor' && config.n8n.errorWorkflowId) settings.errorWorkflow = config.n8n.errorWorkflowId;
    // n8n saves the Webhook node's request headers with each execution, so a login the caller sends (Basic or Header
    // Auth) would sit in every saved run. Such workflows save none; the Message Log is their record, Monitor their alarm.
    if ([...r.nodes.values()].some((n) => n.type === 'n8n-nodes-base.webhook' && (n.config.parameters as { authentication?: string } | undefined)?.authentication)) {
      settings.saveDataSuccessExecution = 'none'; settings.saveDataErrorExecution = 'none';
    }
    const json = toN8nJson(r.meta, r.nodes, r.edges, settings);
    writeFileSync(join(out, `${w}.json`), JSON.stringify(json, null, 2) + '\n');
    summary.push({ workflow: w, name: json.name, nodes: json.nodes.length, connections: r.edges.length });
  }
  writeFileSync(join(out, 'lead-form.html'), leadForm(config));
  return { out, summary };
}

