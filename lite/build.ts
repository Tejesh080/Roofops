/**
 * RoofOps Lite build: one config in, five ready-to-import n8n workflows and a website lead form out.
 *
 *   npx tsx lite/build.ts lite/config/demo.json            -> lite/dist/demo/
 *   npx tsx lite/build.ts lite/config/acme-plumbing.json   -> lite/dist/acme-plumbing/
 *
 * For each workflow in lite/n8n/src it writes:
 *   <name>.sdk.ts  a self-contained n8n Workflow SDK file (config and shared code inlined): create it in n8n with the
 *                  n8n MCP tools (validate_workflow, then create_workflow_from_code)
 *   <name>.json    an n8n workflow export: n8n > Workflows > Import from File
 *   lead-form.html a small enquiry form for the client's website that posts to the lead webhook, with the consent wording
 * Every workflow is exported INACTIVE, with the business timezone and (once n8n.errorWorkflowId is set) [Lite] Monitor as
 * its error workflow. The config is validated first (lite/config/config.ts).
 */
