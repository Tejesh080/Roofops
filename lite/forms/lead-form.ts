/**
 * The website enquiry form for one client (written by lite/build.ts as lite/dist/<client>/lead-form.html). Plain HTML
 * and a few lines of JavaScript: it can be pasted into any website builder (WordPress, Wix, Squarespace "code block")
 * or hosted as a page. It posts JSON to the Lead Follow-Up webhook. Consent boxes start unticked and carry the exact
 * wording from the config, which the workflow records with the contact. The server validates everything again.
 */
import type { LiteConfig } from '../config/config.js';

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

export function leadForm(c: LiteConfig): string {
  const url = `${c.n8n.baseUrl}/webhook/${c.leadIntake.webhookPath}`;
  const services = c.leadIntake.services?.length
    ? `<select id="lf-service" name="service" required><option value="">Choose a service</option>${c.leadIntake.services.map((s) => `<option>${esc(s)}</option>`).join('')}</select>`
    : '<input id="lf-service" name="service" maxlength="120" required>';
  const box = (name: string, text: string) => `<label class="lf-check"><input type="checkbox" name="${name}"> ${esc(text)}</label>`;
  return `<!-- ${esc(c.business.name)}: enquiry form (RoofOps Lite). Posts to ${esc(url)}. Generated by lite/build.ts: edit the config and rebuild. -->
<form id="lite-lead-form" class="lf" novalidate>
  <style>
    .lf{max-width:32rem;display:grid;gap:.75rem;font:inherit}.lf label{display:grid;gap:.25rem}.lf input,.lf select,.lf textarea{font:inherit;padding:.5rem;border:1px solid #888;border-radius:.25rem}
    .lf .lf-check{display:flex;gap:.5rem;align-items:flex-start}.lf .lf-hp{position:absolute;left:-10000px;width:1px;height:1px;overflow:hidden}.lf-msg{min-height:1.5em}
  </style>
  <label>Your name <input name="name" autocomplete="name" maxlength="120" required></label>
  <label>Mobile <input name="phone" type="tel" autocomplete="tel" inputmode="tel" placeholder="04xx xxx xxx"></label>
  <label>Email <input name="email" type="email" autocomplete="email"></label>
  <label>Street address <input name="address" autocomplete="street-address" maxlength="200"></label>
  <label>Suburb <input name="suburb" autocomplete="address-level2" maxlength="80"></label>
  <label>Postcode <input name="postcode" inputmode="numeric" maxlength="4"></label>
  <label for="lf-service">What do you need? ${services}</label>
  <label>Details <textarea name="message" rows="4" maxlength="2000"></textarea></label>
  <fieldset><legend>${esc(c.consent.wording.service)}</legend>
    ${box('consent_sms', 'By SMS')}
    ${box('consent_email', 'By email')}
  </fieldset>
  <fieldset><legend>Optional</legend>
    ${box('consent_reviews', c.consent.wording.reviews)}
    ${box('marketing_opt_in', c.consent.wording.marketing)}
  </fieldset>
  <p><small>Messages come from ${esc(c.business.name)}. Reply STOP at any time to stop them.</small></p>
  <div class="lf-hp" aria-hidden="true"><label>Website <input name="website" tabindex="-1" autocomplete="off"></label></div>
  <button type="submit">Send enquiry</button>
  <p class="lf-msg" role="status"></p>
  <script>
  (function () {
    var f = document.getElementById('lite-lead-form'), msg = f.querySelector('.lf-msg'), busy = false;
    f.addEventListener('submit', function (e) {
      e.preventDefault();
      if (busy) return;                                   // one request per click: the server de-duplicates too
      var d = {}; new FormData(f).forEach(function (v, k) { d[k] = v; });
      ['consent_sms', 'consent_email', 'consent_reviews', 'marketing_opt_in'].forEach(function (k) { d[k] = f.elements[k].checked; });
      if (!d.name || d.name.trim().length < 2) { msg.textContent = 'Please enter your name.'; return; }
      if (!d.phone && !d.email) { msg.textContent = 'Please enter a mobile number or an email address.'; return; }
      d.source = 'Website'; d.source_url = location.href;
      busy = true; f.querySelector('button').disabled = true; msg.textContent = 'Sending...';
      fetch(${JSON.stringify(url)}, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(d) })
        .then(function (r) { return r.json().then(function (b) { return { ok: r.ok, b: b }; }); })
        .then(function (x) {
          if (x.ok && x.b.ok) { f.reset(); msg.textContent = 'Thanks, we have your enquiry and will be in touch.'; }
          else msg.textContent = (x.b.errors || ['Please check your details and try again.']).join(' ');
        })
        .catch(function () { msg.textContent = 'Sorry, that did not go through. Please call ${esc(c.business.phone)}.'; })
        .then(function () { busy = false; f.querySelector('button').disabled = false; });
    });
  })();
  </script>
</form>
`;
}
