/**
 * npm run schema:export
 *
 * LOCAL ONLY (docs/master-plan.md Task 3.1). Loads every migration into a scratch database, schema_export, on a local
 * Postgres and writes what the migrations add up to, so the current definitions can be read without replaying 60-odd
 * files:
 *  - supabase/schema.sql: pg_dump --schema-only --no-owner (grants included), without what changes between runs (the
 *    version lines and pg_dump's random \restrict key);
 *  - supabase/current/functions/<name>.sql: pg_get_functiondef of every function in public that no extension owns,
 *    overloads together.
 * Then drops the scratch database. CI's `schema` job runs it and fails if the committed files differ.
 *
 * The server is ROOFOPS_PG_CONTAINER (default roofops-postgres, reached with docker exec for psql and pg_dump) and
 * SCHEMA_ADMIN_URL (default postgresql://postgres:postgres@127.0.0.1:54322/postgres). It must run Postgres PG_VERSION:
 * pg_dump's output can change between minor versions, so the CI job pins the same one.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { openPostgres } from '../src/db/db.js';
import { migrate } from '../src/db/migrate.js';

export const PG_VERSION = '17.11';
export const SCHEMA_FILE = 'supabase/schema.sql';
export const FUNCTIONS_DIR = 'supabase/current/functions';
export const GENERATED = '-- Generated by scripts/export-current-schema.ts from supabase/migrations. Do not edit: change a migration, then run npm run schema:export.';

/** The dump without what differs between two runs of the same migrations, under the generated-file line. */
export function normaliseDump(dump: string): string {
  const lines = dump.replace(/\r\n/g, '\n').split('\n')
    .filter((l) => !/^\\(un)?restrict /.test(l) && !/^-- Dumped (from database|by pg_dump) version /.test(l));
  return `${GENERATED}\n${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

export interface FunctionDef { name: string; args: string; def: string }

/** One file per function name (<name>.sql), its overloads in signature order. */
export function functionFiles(defs: readonly FunctionDef[]): Map<string, string> {
  const byName = new Map<string, FunctionDef[]>();
  for (const d of defs) byName.set(d.name, [...(byName.get(d.name) ?? []), d]);
  const files = new Map<string, string>();
  const order = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
  for (const name of [...byName.keys()].sort(order)) {
    const body = byName.get(name)!.sort((a, b) => order(a.args, b.args)).map((d) => d.def.trimEnd()).join('\n\n');
    files.set(`${name}.sql`, `${GENERATED}\n\n${body}\n`);
  }
  return files;
}

const FUNCTIONS_SQL = `
  select p.proname as name, pg_get_function_identity_arguments(p.oid) as args, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e')
   order by 1, 2`;

const CONTAINER = process.env.ROOFOPS_PG_CONTAINER || 'roofops-postgres';
const ADMIN_URL = process.env.SCHEMA_ADMIN_URL || 'postgresql://postgres:postgres@127.0.0.1:54322/postgres';
const DB = 'schema_export';

function docker(args: string[]): string {
  const r = spawnSync('docker', args, { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, windowsHide: true });
  if (r.status !== 0) throw new Error(`docker ${args.slice(0, 3).join(' ')}: ${(r.stderr || r.error?.message || '').trim()}`);
  return r.stdout;
}
const psql = (sql: string) => docker(['exec', CONTAINER, 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-Atc', sql]);

async function main() {
  const url = new URL(ADMIN_URL);
  if (!['127.0.0.1', 'localhost', '::1'].includes(url.hostname)) throw new Error(`SCHEMA_ADMIN_URL must be a local server, got ${url.hostname}`);
  url.pathname = `/${DB}`;
  psql(`drop database if exists ${DB} with (force)`);
  psql(`create database ${DB}`);
  try {
    const db = await openPostgres(url.toString());
    let applied: number, defs: FunctionDef[];
    try {
      const [v] = await db.query<{ v: string }>(`select current_setting('server_version') as v`);
      const version = (v?.v ?? '').split(' ')[0] ?? '';
      if (version !== PG_VERSION) {
        throw new Error(`the server runs Postgres ${version || '?'}; generate with ${PG_VERSION} (the CI schema job's image), `
          + 'or change PG_VERSION and that image together');
      }
      applied = (await migrate(db)).applied.length;
      defs = await db.query<FunctionDef>(FUNCTIONS_SQL);
    } finally {
      await db.close();
    }
    const schema = normaliseDump(docker(['exec', CONTAINER, 'pg_dump', '-U', 'postgres', '--schema-only', '--no-owner', DB]));
    writeFileSync(SCHEMA_FILE, schema);
    rmSync(FUNCTIONS_DIR, { recursive: true, force: true });
    mkdirSync(FUNCTIONS_DIR, { recursive: true });
    const files = functionFiles(defs);
    for (const [name, text] of files) writeFileSync(join(FUNCTIONS_DIR, name), text);
    console.log(`${String(applied)} migrations; ${SCHEMA_FILE}: ${String(schema.split('\n').length - 1)} lines; `
      + `${FUNCTIONS_DIR}: ${String(files.size)} files (${String(defs.length)} functions)`);
  } finally {
    psql(`drop database if exists ${DB} with (force)`);
  }
}

/** Only when this file is the entry point: importing it (tests) has no side effect. */
const isMain = (() => {
  try { return realpathSync(process.argv[1] ?? '') === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; }
})();
if (isMain) await main();
